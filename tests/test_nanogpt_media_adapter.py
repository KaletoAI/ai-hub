    async def test_one_public_backend_calls_all_six_modes_with_shared_identity(self):
        """Splitting text/media into separate identities would escape the account cap."""
        raw = Request({"type": "http", "method": "POST", "path": "/",
                       "headers": [], "query_string": b""})
        paths = [
            ("/v1/chat/completions", {"messages": [{"role": "user", "content": "hello"}]}),
            ("/v1/embeddings", {"input": "hello"}),
            ("/v1/audio/speech", {"input": "hello", "voice": "Aria", "response_format": "wav"}),
        ]
        responses = []
        with patch("adapters.httpx.AsyncClient", self.factory):
            for path, body in paths:
                response = await self.ad.dispatch(adapters.NormalizedRequest(
                    path=path, alias="nano/test-model", real_model="test-model",
                    body={"model": "test-model", **body}, raw=raw))
                self.assertEqual(response.status_code, 200)
                responses.append(response)
        self.assertEqual(json.loads(responses[0].body)["choices"][0]["message"]["content"],
                         "a blue triangle")
        self.assertEqual(json.loads(responses[1].body)["data"][0]["embedding"], [0.1, 0.2])
        self.assertEqual(responses[2].body, self.wav)
        with wave.open(io.BytesIO(responses[2].body), "rb") as audio:
            self.assertEqual((audio.getnframes(), audio.getframerate()), (800, 8000))
        image = await self.generate()
        with Image.open(io.BytesIO(image.blobs[0].data)) as decoded:
            self.assertEqual(decoded.size, (3, 3))
        self.create = {"runId": "video-real"}
        video = await self.generate(self.req("video"))
        self.assertEqual(video.blobs[0].data, self.mp4)
        self.create = {"runId": "mesh-real"}
        self.status = {"data": {"status": "COMPLETED", "output": {
            "model_urls": {"glb": "https://cdn.test/mesh.glb"}}}}
        mesh = await self.generate(self.req("3d"))
        self.assertEqual(mesh.blobs[0].data, self.glb)
        self.assertEqual(self.counts, [6, 6])
        self.assertEqual({bid for _, bid in self.slot_ids}, {"nanogpt:nano"})
        submits = [r for r in self.requests if r.method == "POST"]
        self.assertEqual(len(submits), 6)
        self.assertTrue(all(json.loads(r.content)["model"] == "test-model" for r in submits))


    async def test_content_proxy_auth_does_not_follow_redirect_to_asset_host(self):
        """Sora's own authenticated content proxy may redirect to an unauthenticated CDN."""
        self.create = {"runId": "vid-real", "status": "pending"}
        self.status = {"status": "completed",
                       "videoUrl": "https://provider.test/api/generate-video/content?runId=vid-real&model=sora-2"}

        def proxy(req):
            if req.url.path == "/api/generate-video/content":
                self.requests.append(req)
                if req.headers.get("x-api-key") != "provider-secret":
                    return httpx.Response(401)
                return httpx.Response(302, headers={"Location": "https://cdn.test/video.mp4"})
            return self.handle(req)

        self.transport = httpx.MockTransport(proxy)
        result = await self.generate(self.req("video"))
        self.assertEqual((result.blobs[0].kind, result.blobs[0].mime), ("video", "video/mp4"))
        assets = [r for r in self.requests if r.url.host == "cdn.test"]
        self.assertTrue(all("x-api-key" not in r.headers and "authorization" not in r.headers for r in assets))


    async def test_current_reference_slots_are_encoded_not_generic_sixteen_slots(self):
        """The same fresh metadata must govern both validation and body encoding."""
        self.ad.model_catalogs["images"]["test-model"].update(
            capabilities={"text_to_image": True, "image_to_image": True},
            supported_parameters={"max_input_images": 3, "max_output_images": 1,
                                  "quality": ["standard"],
                                  "resolutions": ["512x512"]})
        uploads = {"input_image": self.png, "input_image_2": self.png,
                   "input_image_3": self.png}
        result = await self.generate(self.req(upload_images=uploads,
            params={"quality": "standard", "resolution": "512x512"}))
        self.assertEqual(result.blobs[0].data, self.png)
        submits = [r for r in self.requests if r.method == "POST"]
        self.assertEqual(len(submits), 1)
        body = json.loads(submits[0].content)
        self.assertEqual((body["quality"], body["size"]), ("standard", "512x512"))
        self.assertNotIn("resolution", body)
        self.assertEqual(body["imageDataUrls"],
                         ["data:image/png;base64," + base64.b64encode(self.png).decode()] * 3)
        with self.assertRaises(nanogpt.INPUT_ERROR):
            await self.generate(self.req(upload_images={**uploads, "input_image_4": self.png}))
        self.assertEqual(len([r for r in self.requests if r.method == "POST"]), 1)
        self.assertEqual(self.counts, [1, 1])

def _wav():
    buf = io.BytesIO()
    with wave.open(buf, "wb") as audio:
        audio.setnchannels(1)
        audio.setsampwidth(2)
        audio.setframerate(8000)
        audio.writeframes(b"\x00\x00" * 800)
    return buf.getvalue()


class NanoMedia(unittest.IsolatedAsyncioTestCase):
    def setUp(self):
        self.counts = [0, 0]
        self.progress = []
        self.requests = []
        self.png = _png()
        self.mp4 = _mp4()
        self.wav = _wav()
        self.slot_ids = []
        self.glb = _glb()
        self.obj = b"v 0 0 0\nv 1 0 0\nv 0 1 0\nf 1 2 3\n"
        self.create = {"data": [{"b64_json": base64.b64encode(self.png).decode()}]}
        self.status = {"status": "completed", "videoUrl": "https://cdn.test/video.mp4"}
        self.asset_status = 200
        self.error = None
        self.create_status = 200
        self.catalog_error = None
        self.ctx = adapters.AdapterContext(
            auth_headers=lambda b: {"Authorization": "Bearer " + b["api_key"]},
            inflight_inc=lambda b: (self.slot_ids.append(("inc", b)),
                                   self.counts.__setitem__(0, self.counts[0] + 1)),
            inflight_dec=lambda b: (self.slot_ids.append(("dec", b)),
                                   self.counts.__setitem__(1, self.counts[1] + 1)),
            cost_usd=lambda *a: 0, source_of=lambda r: "test",
            record_call=AsyncMock(), log_enabled=lambda: False,
            note_progress=lambda j, p: self.progress.append((j, p)))
        self.ad = adapters.make_adapter({"name": "nano", "type": "nanogpt",
            "url": "https://provider.test/api", "api_key": "provider-secret",
            "poll_interval": 0, "max_wait": 1, "disconnect_grace": -1}, self.ctx)
        self.transport = httpx.MockTransport(self.handle)
        original = httpx.AsyncClient
        self.factory = lambda **kw: original(transport=self.transport, **kw)

    async def asyncSetUp(self):
        async with self.factory() as client:
            await self.ad.discover(client)
        self.requests.clear()

    def handle(self, req):
        self.requests.append(req)
        if req.url.host == "cdn.test":
            data = (self.png if req.url.path.endswith(".png") else
                    self.glb if req.url.path.endswith(".glb") else
                    self.obj if req.url.path.endswith(".obj") else self.mp4)
            return httpx.Response(self.asset_status, content=data)
        if "models" in req.url.path:
            if self.catalog_error and self.catalog_error in req.url.path:
                return httpx.Response(503)
            return httpx.Response(200, json={"data": [{"id": "test-model",
                "capabilities": {"text_to_speech": True, "text_to_image": True,
                                 "text_to_video": True, "text_to_3d": True},
                "pricing": {"per_image": 1}}]})
        if req.url.path.endswith("/chat/completions"):
            return httpx.Response(200, json={"id": "chat-1", "object": "chat.completion",
                "model": "test-model", "choices": [{"index": 0,
                "message": {"role": "assistant", "content": "a blue triangle"},
                "finish_reason": "stop"}], "usage": {"prompt_tokens": 3, "completion_tokens": 4}})
        if req.url.path.endswith("/embeddings"):
            return httpx.Response(200, json={"object": "list", "model": "test-model",
                "data": [{"object": "embedding", "index": 0, "embedding": [0.1, 0.2]}],
                "usage": {"prompt_tokens": 3, "total_tokens": 3}})
        if req.url.path.endswith("/audio/speech"):
            return httpx.Response(200, content=self.wav, headers={"Content-Type": "audio/wav"})
        if req.url.path.endswith("/status") or "check-midjourney" in req.url.path:
            return httpx.Response(200, json=self.status)
        if self.error:
            raise self.error
        return httpx.Response(self.create_status, json=self.create)

    def req(self, endpoint="images", **kw):
        return adapters.NormalizedRequest(real_model="test-model", inputs={"prompt": "a tree"},
            cloud={"endpoint": endpoint, "options": {}}, job_id="job-1", **kw)

    async def generate(self, req=None):
        with patch("adapters.httpx.AsyncClient", self.factory):
            return await self.ad.generate(req or self.req())

    async def test_refresh_during_preflight_cannot_drop_advertised_output_limit(self):
        """A failed refresh must not turn a bounded paid request into permissive legacy input."""
        self.ad._publish_catalogs({**self.ad.model_catalogs, "images": {
            "test-model": {"supported_parameters": {"max_output_images": 1}},
        }})
        entered, resume = asyncio.Event(), asyncio.Event()
        original = asyncio.to_thread

        async def interleave(function, *args, **kwargs):
            if function is nanogpt.options_of and not entered.is_set():
                entered.set()
                await resume.wait()
            return await original(function, *args, **kwargs)

        with patch("adapters.asyncio.to_thread", interleave), \
                patch("adapters.httpx.AsyncClient", self.factory):
            pending = asyncio.create_task(self.ad.generate(self.req(params={"n": 2})))
            try:
                await asyncio.wait_for(entered.wait(), 5)
                self.catalog_error = "video-models"
                async with self.factory() as client:
                    with self.assertRaises(httpx.HTTPStatusError):
                        await self.ad.discover(client)
            finally:
                resume.set()
            with self.assertRaises(nanogpt.NanoGPTInput):
                await pending
        self.assertFalse(any(r.method == "POST" for r in self.requests))


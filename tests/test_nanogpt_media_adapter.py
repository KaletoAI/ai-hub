def _png():
    buf = io.BytesIO()
    Image.new("RGB", (3, 3), (20, 80, 150)).save(buf, format="PNG")
    return buf.getvalue()


def _glb():
    """Valid GLB with one triangle; no format-shaped fake bytes."""
    doc = {"asset": {"version": "2.0"}, "scene": 0, "scenes": [{"nodes": [0]}],
           "nodes": [{"mesh": 0}], "meshes": [{"primitives": [{"attributes": {"POSITION": 0}}]}],
           "buffers": [{"byteLength": 36}],
           "bufferViews": [{"buffer": 0, "byteOffset": 0, "byteLength": 36}],
           "accessors": [{"bufferView": 0, "componentType": 5126, "count": 3,
                          "type": "VEC3", "min": [0, 0, 0], "max": [1, 1, 0]}]}
    raw = json.dumps(doc).encode()
    raw += b" " * (-len(raw) % 4)
    vertices = struct.pack("<9f", 0, 0, 0, 1, 0, 0, 0, 1, 0)
    return (struct.pack("<4sII", b"glTF", 2, 28 + len(raw) + len(vertices))
            + struct.pack("<I4s", len(raw), b"JSON") + raw
            + struct.pack("<I4s", len(vertices), b"BIN\0") + vertices)


